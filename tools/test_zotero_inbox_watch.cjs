const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const timers = new Map(); let serial = 0;
let now = 1000000;
const context = {Date: {now: () => now},
  setTimeout: (fn, ms) => {timers.set(++serial, {fn, ms}); return serial;}, clearTimeout: id => timers.delete(id)};
vm.createContext(context); vm.runInContext(fs.readFileSync('zotero-support/ui.js', 'utf8'), context);
const ui = context.NotableUI;
async function main() {
  let calls = 0, renders = 0;
  ui.latest = {config: {inbox: 'ToSort', automatic: false, sync_paused: true}, reviews: []};
  ui.view = {closed: false}; ui.tab = 'inbox'; ui.badge = () => {}; ui.message = () => {};
  ui.refreshCollectionNames = () => {};
  ui.render = () => {assert.equal(ui.busy, false); ui.inboxRenderPending = false; renders++;};
  ui.rpc = async method => {assert.equal(method, 'scan_inbox'); calls++; return {config: ui.latest.config, reviews: [{id: 'new'}]};};
  ui.scheduleInbox(); assert.equal(timers.get(ui.inboxTimer).ms, 3000);
  await timers.get(ui.inboxTimer).fn(); assert.equal(calls, 1); assert.equal(renders, 1);
  now += 3000;
  await ui.checkInbox(); assert.equal(calls, 1, 'Idle ticks skip the worker between folder polls');
  now += 12000;
  await ui.checkInbox(); assert.equal(renders, 1, 'Unchanged scans preserve the active form');
  ui.busy = true; await ui.checkInbox(); assert.equal(calls, 2); ui.busy = false;
  ui.drainingFilings = true; await ui.checkInbox(); assert.equal(calls, 2); ui.drainingFilings = false;
  ui.latest.config.tablet_root = 'tablet';
  const discovery = [];
  ui.rpc = async (_, params) => {discovery.push(params.discover); return ui.latest;};
  await ui.checkInbox();
  ui.observeReviewChange('select', 'item');
  now += 15000; await ui.checkInbox();
  ui.observeReviewChange('modify', 'item');
  await ui.checkInbox();
  now += 300000; await ui.checkInbox();
  assert.deepEqual(discovery, [true, false, true, true], 'Discover at startup, after Zotero edits, and on the slower fallback');
  const panel = {}, message = {}, attrs = {}, label = {}, syncStatus = {}, syncDetails = {}, syncStep = {};
  ui.view.document = {getElementById: id => ({activity: panel, message,
    'notable-sync-status': syncStatus, 'notable-sync-details': syncDetails, 'notable-sync-step': syncStep,
    app: {setAttribute: (key, value) => {attrs[key] = value;}},
    'notable-pause': {querySelector: () => label}}[id])};
  let finish;
  ui.rpc = () => new Promise(resolve => {finish = resolve;});
  now += 15000;
  const check = ui.checkInbox();
  assert.equal(ui.busy, true, 'The worker remains serialized during intake');
  let messages = 0;
  ui.message = () => {messages++;};
  ui.receiveProgress({message: 'Checking Zotero file 534 of 537'});
  assert.equal(messages, 0, 'Background progress cannot replace the workspace status');
  ui.updateActivity();
  assert.equal(panel.hidden, true, 'Background polling must never show the loading panel');
  assert.equal(message.hidden, false, 'Ready status must remain visible');
  assert.equal(attrs['aria-busy'], 'false');
  assert.equal(label.textContent, 'Pause sync');
  finish(ui.latest); await check;
  ui.busy = true; ui.updateActivity();
  assert.equal(panel.hidden, false, 'User operations retain the loading panel');
  assert.equal(label.textContent, 'Stop');
  assert.equal(attrs['aria-busy'], 'true');
  ui.busy = false; ui.updateActivity();
  assert.equal(panel.hidden, true);
  ui.busy = true; ui.operation = {method: 'sync', detail: 'Starting…'};
  ui.updateActivity();
  assert.equal(panel.hidden, true, 'Sync uses inline status instead of the activity panel');
  assert.equal(message.hidden, false);
  assert.equal(attrs['aria-busy'], 'false', 'Background sync does not mark the workspace inaccessible');
  assert.equal(label.textContent, 'Pause sync');
  assert.equal(syncDetails.hidden, false);
  assert.equal(syncStatus.textContent, 'Syncing with reMarkable…');
  ui.receiveProgress({message: 'Importing paper 2 of 3'});
  ui.receiveProgress({message: 'Still working...'});
  assert.equal(syncStep.textContent, 'Importing paper 2 of 3', 'A heartbeat keeps the meaningful step visible');
  syncDetails.open = true;
  ui.busy = false; ui.operation = null; ui.updateActivity();
  assert.equal(syncDetails.hidden, true);
  assert.equal(syncDetails.open, false);
  ui.syncFailure = 'Tablet unavailable'; ui.latest.config.sync_paused = false; ui.latest.config.automatic = true;
  ui.updateActivity();
  assert.equal(syncStatus.textContent, 'Sync waiting to retry');
  assert.equal(ui.statusMessage(), 'Tablet unavailable');
  ui.syncFailure = '';
  let modalOpen = false;
  ui.view.document.querySelector = () => modalOpen ? {} : null;
  ui.rpc = () => new Promise(resolve => {finish = resolve;});
  now += 15000;
  const racingScan = ui.checkInbox(); modalOpen = true;
  const beforeModal = renders;
  finish({...ui.latest, reviews: [{id: 'arrived-while-choosing'}]}); await racingScan;
  assert.equal(renders, beforeModal, 'A scan finishing after a dialog opens must not remove it');
  assert.equal(ui.inboxRenderPending, true);
  await ui.checkInbox(); assert.equal(renders, beforeModal);
  modalOpen = false; ui.rpc = async () => ui.latest;
  now += 15000;
  await ui.checkInbox(); assert.equal(renders, beforeModal + 1, 'Render postponed arrivals after the dialog closes');
  ui.rpc = async () => {throw Error('Temporarily unavailable');};
  now += 15000;
  await timers.get(ui.inboxTimer).fn(); assert.equal(ui.busy, false); assert.ok(ui.inboxTimer);
  ui.stopped = true; await timers.get(ui.inboxTimer).fn(); assert.equal(timers.size, 0);
  console.log('PASS: local monitoring with workspace open, sync paused, retries, no repeated renders, busy guards, and shutdown');
}
main().catch(error => {console.error(error); process.exitCode = 1;});
