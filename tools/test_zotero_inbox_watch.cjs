const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const timers = new Map(); let serial = 0;
let now = 1000000;
const context = {Date: {now: () => now},
  setTimeout: (fn, ms) => {timers.set(++serial, {fn, ms}); return serial;}, clearTimeout: id => timers.delete(id)};
vm.createContext(context); vm.runInContext(fs.readFileSync('zotero-support/ui.js', 'utf8'), context);
const ui = context.NotableUI;
async function main() {
  let calls = 0, renders = 0;
  ui.latest = {config: {inbox: 'ToSort', automatic: false, sync_paused: true}, reviews: []};
  const referenceActions = ['Find and attach PDF online', 'Attach downloaded PDF', 'Dismiss this reference']
    .map(label => ({label, dataset: {}}));
  const querySelectorAll = selector => selector === 'button' ? referenceActions : [];
  ui.view = {closed: false, document: {querySelectorAll, getElementById: () => null}};
  ui.tab = 'inbox'; ui.badge = () => {}; ui.message = () => {};
  ui.refreshCollectionNames = () => {};
  ui.render = () => {assert.equal(ui.busy, false); ui.inboxRenderPending = false; renders++;};
  ui.rpc = async method => {assert.equal(method, 'scan_inbox'); calls++; return {config: ui.latest.config, reviews: [{id: 'new'}]};};
  ui.scheduleInbox(); assert.equal(timers.get(ui.inboxTimer).ms, 3000);
  await timers.get(ui.inboxTimer).fn(); assert.equal(calls, 1); assert.equal(renders, 1);
  now += 3000;
  await ui.checkInbox(); assert.equal(calls, 1, 'Idle ticks skip the worker between folder polls');
  now += 12000;
  await ui.checkInbox(); assert.equal(renders, 1, 'Unchanged scans preserve the active form');
  ui.busy = true; await ui.checkInbox(); assert.equal(calls, 2); ui.busy = false;
  ui.drainingFilings = true; await ui.checkInbox(); assert.equal(calls, 2); ui.drainingFilings = false;
  ui.latest.config.tablet_root = 'tablet';
  const discovery = [];
  let fullChecks = 0;
  ui.rpc = async (method, params) => {
    if (method === 'recheck_review') fullChecks++;
    else { assert.equal(method, 'scan_inbox'); discovery.push(params.discover); }
    return ui.latest;
  };
  await ui.checkInbox();
  ui.observeReviewChange('select', 'item');
  now += 15000; await ui.checkInbox();
  ui.observeReviewChange('modify', 'item');
  await ui.checkInbox();
  now += 300000; await ui.checkInbox();
  assert.deepEqual(discovery, [true, false, true, true], 'Discover at startup, after Zotero edits, and on the slower fallback');
  assert.equal(fullChecks, 1, 'Five idle minutes trigger the same local recheck as Check Inbox');
  const settlingChecks = [];
  ui.rpc = async (method, params) => {
    assert.equal(method, 'scan_inbox'); settlingChecks.push(params.discover);
    return {...ui.latest, native_files_settling: settlingChecks.length === 1};
  };
  ui.zoteroInboxDirty = true;
  await ui.checkInbox();
  now += 3000; await ui.checkInbox();
  now += 3000; await ui.checkInbox();
  assert.deepEqual(settlingChecks, [true, true], 'Unsettled native files trigger another discovery on the next idle poll');
  assert.equal(ui.zoteroInboxDirty, false, 'A settled follow-up ends fast discovery');
  const panel = {}, message = {}, attrs = {}, label = {}, syncStatus = {}, syncDetails = {}, syncStep = {};
  const syncProgress = {hidden: false, setAttribute(key, value) {this[key] = value;}, removeAttribute(key) {delete this[key];}};
  ui.view.document = {querySelectorAll, getElementById: id => ({activity: panel, message,
    'notable-sync-status': syncStatus, 'notable-sync-details': syncDetails, 'notable-sync-step': syncStep,
    'notable-sync-progress': syncProgress,
    app: {setAttribute: (key, value) => {attrs[key] = value;}},
    'notable-pause': {querySelector: () => label}}[id])};
  let finish;
  ui.rpc = () => new Promise(resolve => {finish = resolve;});
  now += 15000;
  const check = ui.checkInbox();
  assert.equal(ui.busy, true, 'The worker remains serialized during intake');
  ui.disable(ui.busy); // A selection or render while the background check is running.
  assert.ok(referenceActions.every(button => button.disabled));
  let messages = 0;
  ui.message = () => {messages++;};
  ui.receiveProgress({message: 'Checking Zotero file 534 of 537'});
  assert.equal(messages, 0, 'Background progress cannot replace the workspace status');
  ui.updateActivity();
  assert.equal(panel.hidden, true, 'Background polling must never show the loading panel');
  assert.equal(message.hidden, false, 'Ready status must remain visible');
  assert.equal(attrs['aria-busy'], 'false');
  assert.equal(label.textContent, 'Pause sync');
  const beforeUnchangedCheck = renders;
  finish(ui.latest); await check;
  assert.equal(renders, beforeUnchangedCheck, 'An unchanged scan keeps the active form');
  assert.ok(referenceActions.every(button => !button.disabled), 'The existing PDF and Dismiss buttons are re-enabled');
  ui.busy = true; ui.updateActivity();
  assert.equal(panel.hidden, false, 'User operations retain the loading panel');
  assert.equal(label.textContent, 'Stop');
  assert.equal(attrs['aria-busy'], 'true');
  ui.busy = false; ui.updateActivity();
  assert.equal(panel.hidden, true);
  ui.busy = true; ui.operation = {method: 'sync', detail: 'Starting…'};
  ui.updateActivity();
  assert.equal(panel.hidden, true, 'Sync uses inline status instead of the activity panel');
  assert.equal(message.hidden, false);
  assert.equal(attrs['aria-busy'], 'false', 'Background sync does not mark the workspace inaccessible');
  assert.equal(label.textContent, 'Pause sync');
  assert.equal(syncDetails.hidden, false);
  assert.equal(syncStatus.textContent, 'Syncing with reMarkable…');
  assert.equal(syncProgress.hidden, false, 'The progress bar is visible from the start');
  assert.equal(syncProgress.value, undefined, 'The bar is indeterminate until the tablet paper count is known');
  ui.receiveProgress({message: 'Checking Zotero paper 8 of 10…'});
  assert.equal(syncProgress.value, undefined, 'Preflight counts are separate from the tablet paper count');
  ui.receiveProgress({message: 'Syncing linked paper 2 of 3: A sample paper…'});
  assert.equal(syncProgress.max, 3);
  assert.equal(syncProgress.value, 1);
  const publishing = 'Publishing Results 4 of 9 to Zotero…';
  ui.receiveProgress({message: publishing});
  ui.receiveProgress({message: 'Still working...'});
  assert.equal(syncStep.textContent, publishing, 'A heartbeat keeps the meaningful step visible');
  assert.equal(syncProgress.hidden, false, 'The same bar stays visible while publishing');
  assert.equal(syncProgress.max, 3, 'Numbers in a title do not change the paper count');
  assert.equal(syncProgress.value, 1, 'The bar holds until the paper is finished');
  ui.receiveProgress({message: 'Received tablet PDF 2 of 3…'});
  assert.equal(syncProgress.value, 2);
  const nextPaper = 'Checking new tablet paper 3 of 3: Another paper…';
  ui.receiveProgress({message: nextPaper});
  assert.equal(syncProgress.value, 2, 'Starting the next paper does not move the bar backward');
  const renderIdle = ui.render;
  ui.render = () => {assert.equal(ui.operation.method, 'sync'); renders++;};
  ui.latest.reviews = [{id: 'reference', kind: 'reference'}, {id: 'decision', kind: 'conflict'}];
  const liveInbox = {event: 'progress', inbox_rows: [
    {id: 'reference', kind: 'reference', intake_pdf: {id: 'download'}}, {id: 'download', kind: 'inbox'}]};
  const preDownload = renders;
  ui.receiveProgress(liveInbox);
  ui.receiveProgress(liveInbox);
  assert.equal(renders, preDownload + 1, 'A download refreshes Inbox during sync, with no redundant render');
  assert.equal(ui.latest.reviews[0].intake_pdf.id, 'download');
  assert.equal(ui.latest.reviews[1].id, 'decision', 'Download discovery preserves unrelated review rows');
  assert.equal(ui.latest.reviews[2].id, 'download');
  assert.equal(syncStep.textContent, nextPaper, 'Inbox discovery leaves the sync step visible');
  const reference = ui.latest.reviews[0], messagesBeforeDismissal = messages;
  ui.rpc = (method, params) => {
    assert.equal(method, 'dismiss_reference');
    assert.equal(params.identity, reference.id);
    return new Promise(resolve => {finish = resolve;});
  };
  const dismissal = ui.saveInboxDismissal(reference);
  assert.equal(messages, messagesBeforeDismissal + 1, 'A confirmed dismissal immediately shows that it is being saved');
  assert.equal(ui.latest.reviews[0].id, reference.id, 'Keep the reference visible while saving');
  finish({dismissed_review: reference.id});
  await dismissal;
  assert.equal(ui.latest.reviews.some(row => row.id === reference.id), false, 'A saved dismissal updates Inbox during sync');
  assert.match(ui.saveFeedback.value, /dismissed from Inbox/);
  ui.render = renderIdle;
  syncDetails.open = true;
  ui.busy = false; ui.operation = null; ui.updateActivity();
  assert.equal(syncDetails.hidden, true);
  assert.equal(syncDetails.open, false);
  assert.equal(syncProgress.value, undefined, 'A subsequent sync starts with a fresh progress bar');
  ui.syncFailure = 'Tablet unavailable'; ui.latest.config.sync_paused = false; ui.latest.config.automatic = true;
  ui.updateActivity();
  assert.equal(syncStatus.textContent, 'Sync waiting to retry');
  assert.equal(ui.statusMessage(), 'Tablet unavailable');
  ui.syncFailure = '';
  let modalOpen = false;
  ui.view.document.querySelector = () => modalOpen ? {} : null;
  ui.rpc = () => new Promise(resolve => {finish = resolve;});
  now += 15000;
  const racingScan = ui.checkInbox(); modalOpen = true;
  const beforeModal = renders;
  finish({...ui.latest, reviews: [{id: 'arrived-while-choosing'}]}); await racingScan;
  assert.equal(renders, beforeModal, 'A scan finishing after a dialog opens must not remove it');
  assert.equal(ui.inboxRenderPending, true);
  await ui.checkInbox(); assert.equal(renders, beforeModal);
  modalOpen = false; ui.rpc = async () => ui.latest;
  now += 15000;
  await ui.checkInbox(); assert.equal(renders, beforeModal + 1, 'Render postponed arrivals after the dialog closes');
  ui.rpc = async () => {ui.disable(ui.busy); throw Error('Temporarily unavailable');};
  now += 15000;
  await timers.get(ui.inboxTimer).fn(); assert.equal(ui.busy, false); assert.ok(ui.inboxTimer);
  assert.ok(referenceActions.every(button => !button.disabled), 'A failed background check also unlocks the existing controls');
  ui.stopped = true; await timers.get(ui.inboxTimer).fn(); assert.equal(timers.size, 0);
  console.log('PASS: local monitoring with workspace open, sync paused, retries, no repeated renders, busy guards, and shutdown');
}
main().catch(error => {console.error(error); process.exitCode = 1;});
